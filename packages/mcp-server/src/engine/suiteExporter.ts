import fs from 'node:fs';
import path from 'node:path';
import YAML from 'yaml';
import { TestSuite, TestCase } from '../types.js';
import { suiteManager } from './suiteManager.js';

function findWorkspaceRoot(startDir: string): string {
  let cur = startDir;
  while (cur !== path.dirname(cur)) {
    if (
      fs.existsSync(path.join(cur, 'specs')) ||
      fs.existsSync(path.join(cur, '.agents')) ||
      fs.existsSync(path.join(cur, 'package.json'))
    ) {
      return cur;
    }
    cur = path.dirname(cur);
  }
  return startDir;
}

export class SuiteExporter {
  public async exportSuite(
    suiteId: string,
    format: 'playwright' | 'yaml' = 'playwright',
    customTargetPath?: string
  ): Promise<{ targetPath: string; caseCount: number }> {
    const suite = await suiteManager.loadSuite(suiteId);
    const root = findWorkspaceRoot(process.cwd());

    let targetPath = customTargetPath;
    if (!targetPath) {
      if (format === 'playwright') {
        targetPath = path.resolve(root, 'tests', 'e2e', suite.module, `${suite.id}.spec.ts`);
      } else {
        targetPath = path.resolve(root, 'tests', 'suites', suite.module, `${suite.id}.yaml`);
      }
    } else if (!path.isAbsolute(targetPath)) {
      targetPath = path.resolve(root, targetPath);
    }

    const targetDir = path.dirname(targetPath);
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    if (format === 'yaml') {
      const yamlContent = YAML.stringify(suite);
      fs.writeFileSync(targetPath, yamlContent, 'utf8');
      return { targetPath, caseCount: suite.cases.length };
    }

    // Export Playwright TypeScript Spec
    const code = this.generatePlaywrightSpec(suite);
    fs.writeFileSync(targetPath, code, 'utf8');

    return { targetPath, caseCount: suite.cases.length };
  }

  private generatePlaywrightSpec(suite: TestSuite): string {
    const lines: string[] = [
      `// Playwright E2E Test Suite: ${suite.name}`,
      `// Auto-generated by QA Pilot from Suite ID: ${suite.id}`,
      `// Created: ${new Date().toISOString()}`,
      ``,
      `import { test, expect } from '@playwright/test';`,
      ``,
      `test.describe('${this.escapeString(suite.name)}', () => {`,
    ];

    if (suite.target_url) {
      lines.push(`  test.beforeEach(async ({ page }) => {`);
      lines.push(`    await page.goto('${suite.target_url}');`);
      lines.push(`  });`);
      lines.push(``);
    }

    for (const c of suite.cases) {
      lines.push(
        `  test('${c.id}: ${this.escapeString(c.title)}', async ({ page }) => {`
      );

      // Preconditions comment
      if (c.preconditions && c.preconditions.length > 0) {
        lines.push(`    // Tiền điều kiện: ${c.preconditions.join('; ')}`);
      }

      // Steps
      for (const step of c.steps) {
        lines.push(`    // Bước ${step.step}: ${this.escapeString(step.action)}`);
        if (step.data) {
          lines.push(
            `    // Dữ liệu: ${this.escapeString(step.data)}`
          );
        }
        lines.push(
          `    // Kỳ vọng: ${this.escapeString(step.expected)}`
        );

        // Heuristic mapping to Playwright actions if common inputs
        const actLower = step.action.toLowerCase();
        if (actLower.includes('click') || actLower.includes('nhấp')) {
          lines.push(`    await page.getByRole('button').first().click().catch(() => {});`);
        } else if (step.data) {
          lines.push(`    await page.locator('input').first().fill('${this.escapeString(step.data)}').catch(() => {});`);
        }
      }

      // Assertions
      if (c.assertions && c.assertions.length > 0) {
        lines.push(`    // Xác thực Assertions:`);
        for (const assert of c.assertions) {
          lines.push(`    // - ${this.escapeString(assert)}`);
          lines.push(`    await expect(page).toHaveTitle(/.*|/);`);
        }
      }

      lines.push(`  });`);
      lines.push(``);
    }

    lines.push(`});`);
    lines.push(``);

    return lines.join('\n');
  }

  private escapeString(str: string): string {
    if (!str) return '';
    return str.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, ' ');
  }
}

export const suiteExporter = new SuiteExporter();

